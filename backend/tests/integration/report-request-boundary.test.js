// Independent regression: synthetic historical tenant data + actual SQL roles/RLS.
// This is not evidence of real Supabase JWT, hosted SQL or browser behavior.
import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { createLocalWorkflow } from '../../tools/local-workflow/engine.js';

test('report request authority cannot be forged through client-writable audit logs', async t => {
  const flow = await createLocalWorkflow();
  const { db, scope } = flow;
  const otherOrg = randomUUID(), otherProject = randomUUID(), historicReport = randomUUID();
  const request = randomUUID();
  async function as(role, user, sql, params = []) {
    assert.ok(['authenticated', 'anon', 'service_role'].includes(role));
    await db.exec('set role ' + role);
    try {
      await db.query("select set_config('request.jwt.claim.sub',$1,false)", [user || '']);
      assert.equal((await db.query('select current_user as role')).rows[0].role, role);
      return await db.query(sql, params);
    } finally { await db.exec('reset role'); }
  }
  const lookupSql = 'select * from report_snapshot_request_v2($1,$2,$3,$4,$5,$6)';
  const lookupArgs = [scope.organizationId, scope.projectId, scope.userId, request, 1, 'internal_management'];
  const saveSql = 'select * from generate_report_snapshot_atomic_v2(' + Array.from({ length: 18 }, (_, i) => '$' + (i + 1)).join(',') + ')';
  const snapshot = { claim_purpose: 'internal_management', gross_emissions_snapshot: { gross_total_co2e_kg: 0 }, adjustment_summary: {}, claim_results: {}, adjustment_manifest: [] };
  const saveArgs = [scope.organizationId, scope.projectId, scope.userId, 1, { synthetic: 'A snapshot' }, 'SYNTHETIC-NOT-A-CONTENT-ATTESTATION', '2026-01-01', '2026-12-31', 0, 0, 0, {}, {}, [], 0, '2026-01-15T00:00:00Z', request, snapshot];
  let savedId;
  try {
    // Historical B report was generated by this actor, whose B membership is no
    // longer present. Knowledge of its UUID must not restore access through A.
    await db.query("insert into organizations(id,slug,legal_name,display_name) values($1,$2,'SYNTHETIC B','SYNTHETIC B')", [otherOrg, 'synthetic-report-review-' + otherOrg]);
    await db.query("insert into projects(id,organization_id,project_code,name,reporting_start_date,reporting_end_date) values($1,$2,'SYNTHETIC-B','SYNTHETIC B','2026-01-01','2026-12-31')", [otherProject, otherOrg]);
    await db.query("insert into report_generations(id,organization_id,project_id,generated_by_user_id,status,report_version,payload,payload_hash,reporting_period_start,reporting_period_end,claim_purpose) values($1,$2,$3,$4,'completed',1,$5,'SYNTHETIC','2026-01-01','2026-12-31','internal_management')", [historicReport, otherOrg, otherProject, scope.userId, { synthetic: 'B historical private payload' }]);

    await t.test('an editor can forge an audit event but it grants no historical B report access', async () => {
      assert.deepEqual((await as('authenticated', scope.userId, 'select id from report_generations where id=$1', [historicReport])).rows, []);
      await as('authenticated', scope.userId, "insert into audit_logs(organization_id,project_id,actor_user_id,actor_type,action,entity_type,entity_id,status,metadata) values($1,$2,$3,'edge_function','generate_report_snapshot_atomic_v2','report_generation',$4,'recorded',jsonb_build_object('request_id',$5::text))", [scope.organizationId, scope.projectId, scope.userId, historicReport, request]);
      // RED before the ledger fix: this returned B's row despite normal RLS
      // returning zero. The test retains the attack, not an unsafe old function.
      assert.deepEqual((await as('service_role', null, lookupSql, lookupArgs)).rows, []);
    });

    await t.test('ledger has RLS, no client policy and no anonymous/authenticated privileges', async () => {
      const catalog = (await db.query("select relrowsecurity from pg_class where oid='public.report_snapshot_requests_v2'::regclass")).rows[0];
      assert.equal(catalog.relrowsecurity, true);
      assert.equal(Number((await db.query("select count(*) as n from pg_policy where polrelid='public.report_snapshot_requests_v2'::regclass")).rows[0].n), 0);
      for (const role of ['anon', 'authenticated']) {
        for (const privilege of ['SELECT', 'INSERT', 'UPDATE', 'DELETE']) {
          assert.equal((await db.query("select has_table_privilege($1,'public.report_snapshot_requests_v2',$2) as allowed", [role, privilege])).rows[0].allowed, false);
        }
        await assert.rejects(as(role, role === 'anon' ? null : scope.userId, 'select * from report_snapshot_requests_v2'), { code: '42501' });
        await assert.rejects(as(role, role === 'anon' ? null : scope.userId, 'insert into report_snapshot_requests_v2(organization_id,project_id,request_id,actor_user_id,report_version,claim_purpose,report_generation_id) values($1,$2,$3,$4,1,\'internal_management\',$5)', [scope.organizationId, scope.projectId, randomUUID(), scope.userId, historicReport]), { code: '42501' });
      }
    });

    await t.test('both privileged RPCs reject client roles while service execution remains granted', async () => {
      const signatures = ['report_snapshot_request_v2(uuid,uuid,uuid,text,integer,text)', 'generate_report_snapshot_atomic_v2(uuid,uuid,uuid,integer,jsonb,text,date,date,integer,integer,integer,jsonb,jsonb,jsonb,integer,timestamp with time zone,text,jsonb)'];
      for (const signature of signatures) {
        for (const role of ['anon', 'authenticated', 'service_role']) {
          assert.equal((await db.query('select has_function_privilege($1,$2,\'EXECUTE\') as allowed', [role, signature])).rows[0].allowed, role === 'service_role');
        }
      }
      for (const role of ['anon', 'authenticated']) {
        await assert.rejects(as(role, scope.userId, lookupSql, lookupArgs), { code: '42501' });
        await assert.rejects(as(role, scope.userId, saveSql, saveArgs), { code: '42501' });
      }
    });

    await t.test('legitimate service save ignores forged audit and binds the actual A snapshot', async () => {
      const saved = (await as('service_role', null, saveSql, saveArgs)).rows[0];
      savedId = saved.report_generation_id;
      assert.notEqual(savedId, historicReport);
      const found = (await as('service_role', null, lookupSql, lookupArgs)).rows;
      assert.equal(found.length, 1);
      assert.equal(found[0].id, savedId);
      assert.equal(found[0].organization_id, scope.organizationId);
      assert.equal(found[0].project_id, scope.projectId);
      assert.deepEqual(found[0].payload, { synthetic: 'A snapshot' });
      const retry = (await as('service_role', null, saveSql, saveArgs)).rows[0];
      assert.equal(retry.report_generation_id, savedId);
      assert.equal(Number((await db.query('select count(*) as n from report_snapshot_requests_v2')).rows[0].n), 1);
    });

    await t.test('ledger RLS independently denies rows if a test-only client table grant drifts', async () => {
      // Local catalog mutation only, restored in finally. Exercise RLS itself
      // rather than treating a missing SQL grant as proof of an RLS decision.
      await db.exec('grant select,insert on report_snapshot_requests_v2 to authenticated,anon');
      try {
        for (const role of ['anon', 'authenticated']) {
          assert.deepEqual((await as(role, role === 'anon' ? null : scope.userId, 'select * from report_snapshot_requests_v2')).rows, []);
          await assert.rejects(as(role, role === 'anon' ? null : scope.userId, 'insert into report_snapshot_requests_v2(organization_id,project_id,request_id,actor_user_id,report_version,claim_purpose,report_generation_id) values($1,$2,$3,$4,1,\'internal_management\',$5)', [scope.organizationId, scope.projectId, randomUUID(), scope.userId, savedId]), error => error.code === '42501' && /row-level security/i.test(error.message));
        }
      } finally { await db.exec('revoke all on report_snapshot_requests_v2 from authenticated,anon'); }
    });

    await t.test('scope, actor, version and claim conflicts do not borrow the prior request', async () => {
      const otherEditor = randomUUID();
      await db.query("insert into organization_members(organization_id,user_id,role,status) values($1,$2,'editor','active')", [scope.organizationId, otherEditor]);
      for (const args of [lookupArgs.with(2, otherEditor), lookupArgs.with(4, 2), lookupArgs.with(5, 'not-the-original-claim')]) {
        await assert.rejects(as('service_role', null, lookupSql, args), /report_request_intent_conflict/);
      }
      await assert.rejects(as('service_role', null, lookupSql, lookupArgs.with(1, otherProject)), /report_scope_or_actor_denied/);
      assert.equal((await as('service_role', null, lookupSql, lookupArgs)).rows[0].id, savedId);
    });

    await t.test('snapshot write error rolls back report, ledger and both audit events', async () => {
      const failedRequest = randomUUID();
      await assert.rejects(as('service_role', null, saveSql, saveArgs.with(3, 2).with(16, failedRequest).with(17, { ...snapshot, claim_purpose: 'not-an-enum-value' })));
      assert.equal(Number((await db.query('select count(*) as n from report_generations where organization_id=$1 and project_id=$2', [scope.organizationId, scope.projectId])).rows[0].n), 1);
      assert.equal(Number((await db.query('select count(*) as n from report_snapshot_requests_v2 where request_id=$1', [failedRequest])).rows[0].n), 0);
      assert.equal(Number((await db.query("select count(*) as n from audit_logs where metadata->>'request_id'=$1", [failedRequest])).rows[0].n), 0);
    });

    await t.test('report row scope fence also rejects a malformed service-written ledger binding', async () => {
      const inconsistentRequest = randomUUID();
      await as('service_role', null, 'insert into report_snapshot_requests_v2(organization_id,project_id,request_id,actor_user_id,report_version,claim_purpose,report_generation_id) values($1,$2,$3,$4,1,\'internal_management\',$5)', [scope.organizationId, scope.projectId, inconsistentRequest, scope.userId, historicReport]);
      // Public-only legacy binding is now explicitly unverified, never blessed
      // or used to create a replacement row and never borrowed from tenant B.
      await assert.rejects(as('service_role', null, lookupSql, lookupArgs.with(3, inconsistentRequest)), /REPORT_SNAPSHOT_UNVERIFIED/);
      await assert.rejects(as('service_role', null, saveSql, saveArgs.with(3, 2).with(16, inconsistentRequest)), /REPORT_SNAPSHOT_UNVERIFIED/);
      assert.equal(Number((await db.query('select count(*) as n from report_generations where organization_id=$1 and project_id=$2', [scope.organizationId, scope.projectId])).rows[0].n), 1);
    });
  } finally { await flow.close(); }
});
